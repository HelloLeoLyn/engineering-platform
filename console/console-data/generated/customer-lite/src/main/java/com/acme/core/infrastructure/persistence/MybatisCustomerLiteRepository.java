package com.acme.core.infrastructure.persistence;

import com.acme.core.application.customerlite.CustomerLitePort;
import com.acme.core.application.datascope.DataPermissionContext;
import com.acme.core.application.organization.DepartmentPort;
import com.acme.core.common.core.PageQuery;
import com.acme.core.common.core.PageResult;
import com.acme.core.common.security.DataScope;
import com.acme.core.domain.entity.CustomerLite;
import com.acme.core.infrastructure.persistence.mapper.CustomerLiteMapper;
import com.baomidou.mybatisplus.core.conditions.query.QueryWrapper;

import java.util.List;
import java.util.Optional;
import java.util.Set;

/**
 * MyBatis-Plus implementation of {@link CustomerLitePort} (generated by engineering-platform Generic Module Generator).
 * Data scope enforcement happens HERE at the query boundary: ALL / DEPARTMENT /
 * DEPARTMENT_AND_CHILDREN / SELF. Fail-safe: missing department with a department-
 * dependent scope denies (empty), never upgrades to ALL.
 */
public class MybatisCustomerLiteRepository implements CustomerLitePort {

    private final CustomerLiteMapper customerLiteMapper;
    private final DepartmentPort departmentPort;

    public MybatisCustomerLiteRepository(CustomerLiteMapper customerLiteMapper, DepartmentPort departmentPort) {
        this.customerLiteMapper = customerLiteMapper;
        this.departmentPort = departmentPort;
    }

    @Override
    public Optional<CustomerLite> findById(Long id) {
        return Optional.ofNullable(customerLiteMapper.selectById(id));
    }

    @Override
    public Optional<CustomerLite> findByIdInScope(Long id, DataPermissionContext context) {
        return findByScope(context).stream().filter(e -> e.getId().equals(id)).findFirst();
    }

    @Override
    public List<CustomerLite> findByScope(DataPermissionContext context) {
        QueryWrapper<CustomerLite> wrapper = scopeWrapper(context);
        wrapper.orderByAsc("id");
        return customerLiteMapper.selectList(wrapper);
    }

    @Override
    public PageResult<CustomerLite> findPageByScope(DataPermissionContext context, PageQuery query) {
        QueryWrapper<CustomerLite> countWrapper = scopeWrapper(context);
        long total = customerLiteMapper.selectCount(countWrapper);
        QueryWrapper<CustomerLite> pageWrapper = scopeWrapper(context);
        pageWrapper.orderByAsc("id");
        pageWrapper.last("LIMIT " + query.size() + " OFFSET " + query.offset());
        List<CustomerLite> items = customerLiteMapper.selectList(pageWrapper);
        return PageResult.of(items, total, query.page(), query.size());
    }

    @Override
    public PageResult<CustomerLite> findPageByScopeFiltered(DataPermissionContext context, PageQuery query, String keyword, String status) {
        QueryWrapper<CustomerLite> countWrapper = scopeWrapper(context);
        applyFilters(countWrapper, keyword, status);
        long total = customerLiteMapper.selectCount(countWrapper);
        QueryWrapper<CustomerLite> pageWrapper = scopeWrapper(context);
        applyFilters(pageWrapper, keyword, status);
        pageWrapper.orderByAsc("id");
        pageWrapper.last("LIMIT " + query.size() + " OFFSET " + query.offset());
        List<CustomerLite> items = customerLiteMapper.selectList(pageWrapper);
        return PageResult.of(items, total, query.page(), query.size());
    }

    private void applyFilters(QueryWrapper<CustomerLite> wrapper, String keyword, String status) {
        if (keyword != null && !keyword.isBlank()) {
            wrapper.and(w -> {w.like("code", keyword) .or().like("name", keyword) .or().like("phone", keyword) .or().like("status", keyword) .or().like("level", keyword); });
        }
        if (status != null && !status.isBlank()) {
            wrapper.eq("status", status);
        }
    }

    private QueryWrapper<CustomerLite> scopeWrapper(DataPermissionContext context) {
        QueryWrapper<CustomerLite> wrapper = new QueryWrapper<>();
        DataScope scope = context.scope() == null ? DataScope.SELF : context.scope();
        switch (scope) {
            case ALL -> { }
            case DEPARTMENT -> {
                if (context.departmentId() == null) { wrapper.eq("id", -1L); } else { wrapper.eq("department_id", context.departmentId()); }
            }
            case DEPARTMENT_AND_CHILDREN -> {
                if (context.departmentId() == null) { wrapper.eq("id", -1L); } else {
                    Set<Long> ids = departmentPort.descendantIds(context.departmentId());
                    ids.add(context.departmentId());
                    wrapper.in("department_id", ids);
                }
            }
            case SELF -> {
                if (context.userId() == null) { wrapper.eq("id", -1L); } else { wrapper.eq("created_by", String.valueOf(context.userId())); }
            }
        }
        return wrapper;
    }

    @Override
    public boolean existsByUnique(String value, Long excludeId) {
        QueryWrapper<CustomerLite> wrapper = new QueryWrapper<>();
        wrapper.eq("code", value);
        if (excludeId != null) { wrapper.ne("id", excludeId); }
        return customerLiteMapper.selectCount(wrapper) > 0;
    }

    @Override
    public CustomerLite insert(CustomerLite entity) {
        customerLiteMapper.insert(entity);
        return entity;
    }

    @Override
    public int update(CustomerLite entity) {
        return customerLiteMapper.updateById(entity);
    }
}
