package com.acme.core;

import com.acme.core.api.auth.LoginRequest;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.web.client.TestRestTemplate;
import org.springframework.boot.test.web.server.LocalServerPort;
import org.springframework.http.HttpEntity;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpMethod;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.test.context.ActiveProfiles;

import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Real HTTP Data Permission E2E (generated by engineering-platform 0.1.0).
 *
 * Boots the real application (random port) and performs real HTTP calls to prove
 * that ALL / DEPARTMENT / DEPARTMENT_AND_CHILDREN / SELF return different, correct
 * data sets. Test-only credentials live in the test seed (application-test.yml).
 *
 * Seed layout (see seed-z-data-permission.sql + seed-zzz-product.sql):
 *   departments: 1=HQ(root) 2=Sales(1) 3=Sales-East(2) 4=Finance(1) 5=Disabled-Dept(1, disabled)
 *   users: admin@HQ(sales-manager too), viewer@HQ, disabled@Sales,
 *          sales-manager@Sales, sales-user@Sales, finance-user@Finance, self-user@HQ
 *   products: 1=HQ/admin, 2+3=Sales, 4=Sales-East, 5=Finance, 6=self-user
 */
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT)
@ActiveProfiles("test")
class DataScopeE2ETest {

    @LocalServerPort
    private int port;

    @Autowired
    private TestRestTemplate rest;

    private String url(String path) {
        return "http://localhost:" + port + path;
    }

    private ResponseEntity<Map> login(String username, String password) {
        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.APPLICATION_JSON);
        HttpEntity<LoginRequest> body = new HttpEntity<>(new LoginRequest(username, password), headers);
        return rest.postForEntity(url("/api/auth/login"), body, Map.class);
    }

    private String token(String username, String password) {
        ResponseEntity<Map> response = login(username, password);
        assertThat(response.getStatusCode()).isEqualTo(HttpStatus.OK);
        Map data = (Map) response.getBody().get("data");
        return (String) data.get("token");
    }

    private ResponseEntity<Map> products(String token) {
        HttpHeaders headers = new HttpHeaders();
        headers.setBearerAuth(token);
        return rest.exchange(url("/api/products"), HttpMethod.GET,
                new HttpEntity<>(headers), Map.class);
    }

    @SuppressWarnings("unchecked")
    private int productCount(String token) {
        ResponseEntity<Map> response = products(token);
        assertThat(response.getStatusCode()).isEqualTo(HttpStatus.OK);
        Map body = response.getBody();
        Map data = (Map) body.get("data");
        List<Map> items = (List<Map>) data.get("items");
        return items == null ? 0 : items.size();
    }

    // A. ALL (admin has ALL via role merge) -> all seed products visible
    // (other tests may create extra HQ products, so assert >= seed count)
    @Test
    void allScopeReturnsAllProducts() {
        String token = token("admin", "admin123");
        assertThat(productCount(token)).isGreaterThanOrEqualTo(6);
    }

    // B. DEPARTMENT (sales-user, dept=Sales=2) -> 2 products in Sales
    @Test
    void departmentScopeReturnsOwnDepartmentOnly() {
        String token = token("sales-user", "admin123");
        assertThat(productCount(token)).isEqualTo(2);
    }

    // C. DEPARTMENT_AND_CHILDREN (sales-manager, dept=Sales=2) -> Sales + Sales-East = 3
    @Test
    void departmentAndChildrenScopeIncludesDescendants() {
        String token = token("sales-manager", "admin123");
        assertThat(productCount(token)).isEqualTo(3);
    }

    // D. SELF (self-user created_by=7 -> 1 product)
    @Test
    void selfScopeReturnsOnlyOwnData() {
        String token = token("self-user", "admin123");
        assertThat(productCount(token)).isEqualTo(1);
    }

    // E. No product read permission -> 403
    @Test
    void missingPermissionDenied() {
        String token = token("viewer", "admin123");
        assertThat(products(token).getStatusCode()).isEqualTo(HttpStatus.FORBIDDEN);
    }

    // F. No token -> 401
    @Test
    void anonymousDenied() {
        ResponseEntity<Map> response = rest.exchange(
                url("/api/products"), HttpMethod.GET, HttpEntity.EMPTY, Map.class);
        assertThat(response.getStatusCode()).isEqualTo(HttpStatus.UNAUTHORIZED);
    }

    // G. Disabled user cannot login; disabled department filtered from normal scope
    @Test
    void disabledUserRejectedAndDisabledDepartmentExcluded() {
        ResponseEntity<Map> login = login("disabled", "admin123");
        assertThat(login.getStatusCode()).isEqualTo(HttpStatus.FORBIDDEN);
        assertThat(String.valueOf(((Map) login.getBody().get("error")).get("code")))
                .contains("USER_DISABLED");
    }

    // Multi-role deterministic merge: admin has roles admin(ALL) + sales-manager(DEPARTMENT_AND_CHILDREN)
    // -> ALL wins; self-user SELF -> 1 own product
    @Test
    void multiRoleMergeAllWins() {
        String token = token("admin", "admin123");
        assertThat(productCount(token)).isGreaterThanOrEqualTo(6); // ALL wins over DEPARTMENT_AND_CHILDREN
    }

    @Test
    void departmentScopeFinanceIsIsolated() {
        String token = token("finance-user", "admin123");
        assertThat(productCount(token)).isEqualTo(1);
    }

    // Department tree: stable, parent/children correct, disabled flagged
    @Test
    void departmentTreeIsStableAndFlagsDisabled() {
        String token = token("admin", "admin123");
        HttpHeaders headers = new HttpHeaders();
        headers.setBearerAuth(token);
        ResponseEntity<Map> response = rest.exchange(url("/api/departments/tree"),
                HttpMethod.GET, new HttpEntity<>(headers), Map.class);
        assertThat(response.getStatusCode()).isEqualTo(HttpStatus.OK);
        List<Map> roots = (List<Map>) response.getBody().get("data");
        assertThat(roots).hasSize(1); // HQ root only
        Map hq = roots.get(0);
        List<Map> children = (List<Map>) hq.get("children");
        assertThat(children).hasSizeGreaterThanOrEqualTo(3); // Sales, Finance, Disabled-Dept (+ any mgmt-test depts)
    }
}
