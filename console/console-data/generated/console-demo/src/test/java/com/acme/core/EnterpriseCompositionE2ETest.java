package com.acme.core;

import com.acme.core.api.auth.LoginRequest;
import com.acme.core.application.operationlog.OperationLogPort;
import com.acme.core.domain.entity.SysOperationLog;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.web.client.TestRestTemplate;
import org.springframework.boot.test.web.server.LocalServerPort;
import org.springframework.http.HttpEntity;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpMethod;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.test.context.ActiveProfiles;

import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Real HTTP Enterprise Composition E2E (generated by engineering-platform 0.1.0).
 *
 * One full business chain proving the Enterprise Foundation assets work together
 * (not isolated): login → menu → dictionary → create product → list product →
 * update product → disable product → operation log persistence.
 */
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT)
@ActiveProfiles("test")
class EnterpriseCompositionE2ETest {

    @LocalServerPort
    private int port;

    @Autowired
    private TestRestTemplate rest;

    @Autowired
    private OperationLogPort operationLogPort;

    private String url(String path) {
        return "http://localhost:" + port + path;
    }

    private ResponseEntity<Map> login(String username, String password) {
        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.APPLICATION_JSON);
        HttpEntity<LoginRequest> body = new HttpEntity<>(new LoginRequest(username, password), headers);
        return rest.postForEntity(url("/api/auth/login"), body, Map.class);
    }

    private String token(String username, String password) {
        ResponseEntity<Map> response = login(username, password);
        assertThat(response.getStatusCode()).isEqualTo(HttpStatus.OK);
        Map data = (Map) response.getBody().get("data");
        return (String) data.get("token");
    }

    private HttpEntity<String> json(String token, String body) {
        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.APPLICATION_JSON);
        headers.setBearerAuth(token);
        return new HttpEntity<>(body, headers);
    }

    private ResponseEntity<Map> get(String token, String path) {
        HttpHeaders headers = new HttpHeaders();
        headers.setBearerAuth(token);
        return rest.exchange(url(path), HttpMethod.GET, new HttpEntity<>(headers), Map.class);
    }

    private ResponseEntity<Map> post(String token, String path, String body) {
        return rest.exchange(url(path), HttpMethod.POST, json(token, body), Map.class);
    }

    private ResponseEntity<Map> put(String token, String path, String body) {
        return rest.exchange(url(path), HttpMethod.PUT, json(token, body), Map.class);
    }

    @SuppressWarnings("unchecked")
    @Test
    void fullBusinessChain() {
        // 1. login (Authentication)
        String token = token("admin", "admin123");

        // 2. menu (Menu + RBAC filtering)
        ResponseEntity<Map> menus = get(token, "/api/menus/me");
        assertThat(menus.getStatusCode()).isEqualTo(HttpStatus.OK);
        List<Map> menuTree = (List<Map>) menus.getBody().get("data");
        assertThat(menuTree).isNotEmpty();

        // 3. dictionary (Dictionary)
        ResponseEntity<Map> dict = get(token, "/api/dictionaries/product_status/items");
        assertThat(dict.getStatusCode()).isEqualTo(HttpStatus.OK);
        List<Map> statusItems = (List<Map>) dict.getBody().get("data");
        assertThat(statusItems).extracting(m -> m.get("value"))
                .contains("ENABLED", "DISABLED");

        // 4. create product (Platform Core + RBAC + Data Permission + Operation Log)
        ResponseEntity<Map> created = post(token, "/api/products",
                "{\"code\":\"COMP-001\",\"name\":\"Composition Widget\",\"status\":\"ENABLED\",\"category\":\"ELECTRONIC\"}");
        assertThat(created.getStatusCode()).isEqualTo(HttpStatus.OK);
        Map createdData = (Map) created.getBody().get("data");
        Object id = createdData.get("id");
        assertThat(createdData.get("createdBy")).isEqualTo(1);

        // 5. list product (Data Permission scope)
        ResponseEntity<Map> list = get(token, "/api/products");
        assertThat(list.getStatusCode()).isEqualTo(HttpStatus.OK);
        Map listData = (Map) list.getBody().get("data");
        assertThat(((Number) listData.get("total")).longValue()).isGreaterThanOrEqualTo(7);

        // 6. update product (RBAC + Operation Log)
        ResponseEntity<Map> updated = put(token, "/api/products/" + id,
                "{\"code\":\"COMP-001\",\"name\":\"Composition Widget v2\",\"status\":\"ENABLED\",\"category\":\"MECHANICAL\"}");
        assertThat(updated.getStatusCode()).isEqualTo(HttpStatus.OK);
        assertThat(((Map) updated.getBody().get("data")).get("name")).isEqualTo("Composition Widget v2");

        // 7. disable product (Operation Log)
        ResponseEntity<Map> disabled = post(token, "/api/products/" + id + "/disable", "{}");
        assertThat(disabled.getStatusCode()).isEqualTo(HttpStatus.OK);
        assertThat(((Map) disabled.getBody().get("data")).get("status")).isEqualTo("DISABLED");

        // 8. operation log persistence (Operation Log, real DB query)
        List<SysOperationLog> logs = operationLogPort.findLatest(50);
        assertThat(logs).extracting(SysOperationLog::getOperation)
                .contains("PRODUCT_CREATE", "PRODUCT_UPDATE", "PRODUCT_DISABLE");
        SysOperationLog createLog = logs.stream()
                .filter(l -> "PRODUCT_CREATE".equals(l.getOperation())).findFirst().orElseThrow();
        assertThat(createLog.getUserId()).isEqualTo(1L);
        assertThat(createLog.getResourceType()).isEqualTo("PRODUCT");
        assertThat(createLog.getRequestId()).isNotBlank();
        assertThat(createLog.getCorrelationId()).isNotBlank();
        assertThat(createLog.getOccurredAt()).isNotNull();
        // sensitive-data safety: no password/token/secret persisted
        for (SysOperationLog log : logs) {
            String json = log.toString();
            assertThat(json).doesNotContain("password");
            assertThat(json).doesNotContain("secret");
            assertThat(json).doesNotContain("Bearer");
        }
    }
}
