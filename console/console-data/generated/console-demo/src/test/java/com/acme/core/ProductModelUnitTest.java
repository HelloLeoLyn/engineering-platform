import com.acme.core.domain.entity.DictionaryItem;
import com.acme.core.domain.entity.DictionaryType;
import com.acme.core.domain.entity.Product;
import org.junit.jupiter.api.Test;

import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * Product service/model unit tests (generated by engineering-platform 0.1.0).
 *
 * Covers: create validation (code/name/status/category/duplicate), detail
 * enforcement, page/list, update (immutable createdBy/departmentId), disable,
 * data-scope filtering at the port level.
 */
class ProductModelUnitTest {

    /** In-memory ProductPort with optional scope filter and duplicate detection. */
    private static final class StubPort implements ProductPort {
        final List<Product> rows = new ArrayList<>();
        Long nextId = 100L;
        DataPermissionContext scopeContext;

        @Override
        public Optional<Product> findById(Long id) {
            return rows.stream().filter(p -> p.getId().equals(id)).findFirst();
        }

        @Override
        public Optional<Product> findByIdInScope(Long id, DataPermissionContext context) {
            return findByScope(context).stream().filter(p -> p.getId().equals(id)).findFirst();
        }

        @Override
        public List<Product> findByScope(DataPermissionContext context) {
            return rows.stream().filter(p -> visible(p, context)).toList();
        }

        @Override
        public PageResult<Product> findPageByScope(
                DataPermissionContext context, PageQuery query) {
            List<Product> scoped = findByScope(context);
            return PageResult.of(scoped, scoped.size(),
                    query.page(), query.size());
        }

        @Override
        public PageResult<Product> findPageByScopeFiltered(
                DataPermissionContext context, PageQuery query,
                String keyword, String status, String category) {
            List<Product> scoped = findByScope(context).stream()
                    .filter(p -> keyword == null || keyword.isBlank()
                            || p.getCode().contains(keyword) || p.getName().contains(keyword))
                    .filter(p -> status == null || status.isBlank() || status.equals(p.getStatus()))
                    .filter(p -> category == null || category.isBlank() || category.equals(p.getCategory()))
                    .toList();
            return PageResult.of(scoped, scoped.size(),
                    query.page(), query.size());
        }

        private boolean visible(Product p, DataPermissionContext context) {
            if (context == null || context.scope() == null || context.scope() == DataScope.ALL) {
                return true;
            }
            return switch (context.scope()) {
                case DEPARTMENT -> p.getDepartmentId() != null
                        && p.getDepartmentId().equals(context.departmentId());
                case DEPARTMENT_AND_CHILDREN -> p.getDepartmentId() != null
                        && p.getDepartmentId().equals(context.departmentId());
                case SELF -> p.getCreatedBy() != null
                        && p.getCreatedBy().equals(context.userId());
                default -> true;
            };
        }

        @Override
        public boolean existsByCode(String code, Long excludeId) {
            return rows.stream().anyMatch(p -> p.getCode().equals(code)
                    && (excludeId == null || !p.getId().equals(excludeId)));
        }

        @Override
        public Product insert(Product product) {
            product.setId(nextId++);
            rows.add(product);
            return product;
        }

        @Override
        public int update(Product product) {
            for (int i = 0; i < rows.size(); i++) {
                if (rows.get(i).getId().equals(product.getId())) {
                    rows.set(i, product);
                    return 1;
                }
            }
            return 0;
        }
    }

    private static final class StubDictionary implements DictionaryPort {
        @Override
        public Optional<DictionaryType> findTypeByCode(String code) {
            if ("product_status".equals(code)) {
                DictionaryType t = new DictionaryType();
                t.setId(4L);
                t.setCode("product_status");
                t.setEnabled(true);
                return Optional.of(t);
            }
            return Optional.empty();
        }

        @Override
        public List<DictionaryItem> findItemsByTypeId(Long typeId) {
            DictionaryItem enabled = new DictionaryItem();
            enabled.setValue("ENABLED");
            DictionaryItem disabled = new DictionaryItem();
            disabled.setValue("DISABLED");
            return List.of(enabled, disabled);
        }
    }

    private static final DataPermissionContext ALL = DataPermissionContext.of(1L, 1L, DataScope.ALL);

    private final StubPort port = new StubPort();
    private final ProductService service = new ProductService(port, new StubDictionary());

    // create: success path with server-side owner fields
    @Test
    void createPersistsWithOwnerFromRequestContext() {
        ProductResponse created = service.create(
                new ProductCreateRequest("PRD-X", "Widget", "ENABLED", "ELECTRONIC"), 42L, 7L);
        assertThat(created.id()).isNotNull();
        assertThat(created.createdBy()).isEqualTo(42L);
        assertThat(created.departmentId()).isEqualTo(7L);
        assertThat(created.status()).isEqualTo("ENABLED");
        assertThat(port.rows).hasSize(1);
    }

    // create: duplicate code rejected
    @Test
    void createRejectsDuplicateCode() {
        service.create(new ProductCreateRequest("PRD-1", "A", null, null), 1L, 1L);
        assertThatThrownBy(() -> service.create(
                new ProductCreateRequest("PRD-1", "B", null, null), 1L, 1L))
                .isInstanceOfSatisfying(PlatformException.class,
                        e -> assertThat(e.errorCode().code()).isEqualTo("PRODUCT_CODE_DUPLICATE"));
    }

    // create: code/name required + status validated against dictionary
    @Test
    void createRejectsInvalidInput() {
        assertThatThrownBy(() -> service.create(
                new ProductCreateRequest(null, "A", null, null), 1L, 1L))
                .isInstanceOfSatisfying(PlatformException.class,
                        e -> assertThat(e.errorCode().code()).isEqualTo("PRODUCT_CODE_REQUIRED"));
        assertThatThrownBy(() -> service.create(
                new ProductCreateRequest("PRD-1", "", null, null), 1L, 1L))
                .isInstanceOfSatisfying(PlatformException.class,
                        e -> assertThat(e.errorCode().code()).isEqualTo("PRODUCT_NAME_REQUIRED"));
        assertThatThrownBy(() -> service.create(
                new ProductCreateRequest("PRD-1", "A", "BOGUS", null), 1L, 1L))
                .isInstanceOfSatisfying(PlatformException.class,
                        e -> assertThat(e.errorCode().code()).isEqualTo("PRODUCT_STATUS_INVALID"));
    }

    // detail: out-of-scope product not exposed
    @Test
    void detailHidesOutOfScopeProduct() {
        Product p = new Product();
        p.setId(1L);
        p.setCode("PRD-1");
        p.setName("A");
        p.setDepartmentId(2L);
        p.setCreatedBy(1L);
        port.rows.add(p);

        DataPermissionContext self = DataPermissionContext.of(99L, 99L, DataScope.SELF);
        assertThatThrownBy(() -> service.get(1L, self))
                .isInstanceOfSatisfying(PlatformException.class,
                        e -> assertThat(e.errorCode().code()).isEqualTo("PRODUCT_NOT_FOUND"));
        // same user owns it -> visible
        DataPermissionContext owner = DataPermissionContext.of(1L, 1L, DataScope.SELF);
        assertThat(service.get(1L, owner).code()).isEqualTo("PRD-1");
    }

    // list: only scoped rows
    @Test
    void listFiltersByScope() {
        Product a = new Product();
        a.setId(1L);
        a.setCode("A");
        a.setName("A");
        a.setDepartmentId(1L);
        a.setCreatedBy(1L);
        Product b = new Product();
        b.setId(2L);
        b.setCode("B");
        b.setName("B");
        b.setDepartmentId(2L);
        b.setCreatedBy(2L);
        port.rows.addAll(List.of(a, b));

        assertThat(service.list(DataPermissionContext.of(1L, 1L, DataScope.SELF))).hasSize(1);
        assertThat(service.page(PageQuery.of(1, 10), DataPermissionContext.of(1L, 1L, DataScope.ALL))
                .total()).isEqualTo(2);
    }

    // update: immutable owner fields never changed
    @Test
    void updateKeepsOwnerFields() {
        Product p = new Product();
        p.setId(1L);
        p.setCode("PRD-1");
        p.setName("Old");
        p.setStatus("ENABLED");
        p.setDepartmentId(1L);
        p.setCreatedBy(1L);
        port.rows.add(p);

        ProductResponse updated = service.update(1L,
                new ProductUpdateRequest("PRD-1", "New", "DISABLED", "MECHANICAL"), ALL);
        assertThat(updated.name()).isEqualTo("New");
        assertThat(updated.status()).isEqualTo("DISABLED");
        assertThat(updated.createdBy()).isEqualTo(1L);
        assertThat(updated.departmentId()).isEqualTo(1L);
    }

    // disable: status transitions, out-of-scope denied
    @Test
    void disableTransitionsStatusAndEnforcesScope() {
        Product p = new Product();
        p.setId(1L);
        p.setCode("PRD-1");
        p.setName("A");
        p.setStatus("ENABLED");
        p.setDepartmentId(1L);
        p.setCreatedBy(1L);
        port.rows.add(p);

        assertThat(service.disable(1L, ALL).status()).isEqualTo("DISABLED");
        assertThatThrownBy(() -> service.disable(1L,
                DataPermissionContext.of(99L, 99L, DataScope.SELF)))
                .isInstanceOfSatisfying(PlatformException.class,
                        e -> assertThat(e.errorCode().code()).isEqualTo("PRODUCT_NOT_FOUND"));
    }
}
