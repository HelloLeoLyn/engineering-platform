package com.acme.core.api.product;

import com.acme.core.application.datascope.DataPermissionContext;
import com.acme.core.application.datascope.DataScopeResolver;
import com.acme.core.application.product.ProductCreateRequest;
import com.acme.core.application.product.ProductResponse;
import com.acme.core.application.product.ProductService;
import com.acme.core.application.product.ProductUpdateRequest;
import com.acme.core.common.core.ApiResponse;
import com.acme.core.common.core.PageQuery;
import com.acme.core.common.core.PageResult;
import com.acme.core.common.core.PlatformException;
import com.acme.core.common.core.RequestContext;
import com.acme.core.common.security.OperationLog;
import com.acme.core.common.security.RequirePermission;
import com.acme.core.common.security.SecurityErrorCodes;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import java.util.List;

/**
 * Reference Product CRUD API (generated by engineering-platform 0.1.0).
 *
 * Validation host consuming the whole V0.4 Enterprise Foundation:
 *   Platform Core (ApiResponse/PageQuery/PageResult/RequestContext)
 *   Authentication (AuthInterceptor fills RequestContext)
 *   RBAC (@RequirePermission)
 *   Organization/Data Permission (DataScopeResolver per request)
 *   Operation Log (@OperationLog on write operations)
 */
@RestController
@RequestMapping("/api/products")
public class ProductController {

    private final ProductService productService;
    private final DataScopeResolver dataScopeResolver;

    public ProductController(ProductService productService, DataScopeResolver dataScopeResolver) {
        this.productService = productService;
        this.dataScopeResolver = dataScopeResolver;
    }

    private Long currentUserId() {
        return Long.valueOf(RequestContext.currentUserId()
                .orElseThrow(() -> new PlatformException(SecurityErrorCodes.UNAUTHENTICATED)));
    }

    private DataPermissionContext scope() {
        return dataScopeResolver.resolve(currentUserId());
    }

    @PostMapping
    @RequirePermission("product:item:create")
    @OperationLog(operation = "PRODUCT_CREATE", resourceType = "PRODUCT")
    public ApiResponse<ProductResponse> create(@RequestBody ProductCreateRequest request) {
        Long userId = currentUserId();
        Long departmentId = RequestContext.currentDepartmentId()
                .map(Long::valueOf).orElse(null);
        return ApiResponse.ofSuccess(productService.create(request, userId, departmentId));
    }

    @GetMapping("/{id}")
    @RequirePermission("product:item:read")
    public ApiResponse<ProductResponse> detail(@PathVariable Long id) {
        return ApiResponse.ofSuccess(productService.get(id, scope()));
    }

    @GetMapping
    @RequirePermission("product:item:read")
    public ApiResponse<PageResult<ProductResponse>> list(
            @RequestParam(defaultValue = "1") int page,
            @RequestParam(defaultValue = "20") int size,
            @RequestParam(required = false) String keyword,
            @RequestParam(required = false) String status,
            @RequestParam(required = false) String category) {
        if (keyword == null && status == null && category == null) {
            return ApiResponse.ofSuccess(productService.page(PageQuery.of(page, size), scope()));
        }
        return ApiResponse.ofSuccess(productService.pageFiltered(PageQuery.of(page, size), scope(),
                keyword, status, category));
    }

    @PutMapping("/{id}")
    @RequirePermission("product:item:update")
    @OperationLog(operation = "PRODUCT_UPDATE", resourceType = "PRODUCT")
    public ApiResponse<ProductResponse> update(@PathVariable Long id,
                                               @RequestBody ProductUpdateRequest request) {
        return ApiResponse.ofSuccess(productService.update(id, request, scope()));
    }

    @PostMapping("/{id}/disable")
    @RequirePermission("product:item:disable")
    @OperationLog(operation = "PRODUCT_DISABLE", resourceType = "PRODUCT")
    public ApiResponse<ProductResponse> disable(@PathVariable Long id) {
        return ApiResponse.ofSuccess(productService.disable(id, scope()));
    }
}
