package com.acme.core.infrastructure.persistence;

import com.acme.core.application.organization.DepartmentPort;
import com.acme.core.application.rbac.PermissionManagementPort;
import com.acme.core.application.rbac.PermissionManagementService;
import com.acme.core.application.rbac.RoleManagementPort;
import com.acme.core.application.rbac.RoleManagementService;
import com.acme.core.application.rbac.UserManagementPort;
import com.acme.core.application.rbac.UserManagementService;
import com.acme.core.application.rbac.UserQueryPort;
import com.acme.core.application.rbac.UserQueryService;
import com.acme.core.infrastructure.persistence.mapper.SysPermissionMapper;
import com.acme.core.infrastructure.persistence.mapper.SysRoleMapper;
import com.acme.core.infrastructure.persistence.mapper.SysRolePermissionMapper;
import com.acme.core.infrastructure.persistence.mapper.SysUserMapper;
import com.acme.core.infrastructure.persistence.mapper.SysUserRoleMapper;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * RBAC bean wiring (generated by engineering-platform 0.1.0).
 * MyBatis implementations are wired as the stable application contracts
 * (UserQueryPort / UserManagementPort / RoleManagementPort / PermissionManagementPort);
 * application services depend only on those contracts.
 */
@Configuration
public class RbacBeansConfig {

    @Bean
    public UserQueryPort userQueryPort(SysUserMapper userMapper, SysRoleMapper roleMapper,
                                       SysPermissionMapper permissionMapper,
                                       SysUserRoleMapper userRoleMapper,
                                       SysRolePermissionMapper rolePermissionMapper) {
        return new MybatisUserQueryRepository(userMapper, roleMapper, permissionMapper,
                userRoleMapper, rolePermissionMapper);
    }

    @Bean
    public UserQueryService userQueryService(UserQueryPort userQueryPort) {
        return new UserQueryService(userQueryPort);
    }

    @Bean
    public UserManagementPort userManagementPort(SysUserMapper userMapper,
                                                 SysUserRoleMapper userRoleMapper,
                                                 SysRoleMapper roleMapper) {
        return new MybatisUserManagementRepository(userMapper, userRoleMapper, roleMapper);
    }

    @Bean
    public UserManagementService userManagementService(UserManagementPort userManagementPort,
                                                       DepartmentPort departmentPort) {
        return new UserManagementService(userManagementPort, departmentPort);
    }

    @Bean
    public RoleManagementPort roleManagementPort(SysRoleMapper roleMapper,
                                                 SysRolePermissionMapper rolePermissionMapper,
                                                 SysPermissionMapper permissionMapper) {
        return new MybatisRoleManagementRepository(roleMapper, rolePermissionMapper, permissionMapper);
    }

    @Bean
    public RoleManagementService roleManagementService(RoleManagementPort roleManagementPort) {
        return new RoleManagementService(roleManagementPort);
    }

    @Bean
    public PermissionManagementPort permissionManagementPort(SysPermissionMapper permissionMapper) {
        return new MybatisPermissionManagementRepository(permissionMapper);
    }

    @Bean
    public PermissionManagementService permissionManagementService(
            PermissionManagementPort permissionManagementPort) {
        return new PermissionManagementService(permissionManagementPort);
    }
}
