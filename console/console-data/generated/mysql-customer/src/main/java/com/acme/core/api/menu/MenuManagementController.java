package com.acme.core.api.menu;

import com.acme.core.application.menu.MenuManagementService;
import com.acme.core.application.menu.MenuService;
import com.acme.core.common.core.ApiResponse;
import com.acme.core.common.security.OperationLog;
import com.acme.core.common.security.RequirePermission;
import com.acme.core.domain.entity.SysMenu;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import java.util.List;
import java.util.Map;

/**
 * Menu management API (generated by engineering-platform 0.1.0).
 * Menu ≠ Authorization: menu.permissionCode only references permissions for
 * navigation visibility; backend @RequirePermission stays the security boundary.
 */
@RestController
@RequestMapping("/api/menus")
public class MenuManagementController {

    private final MenuManagementService managementService;
    private final MenuService menuService;

    public MenuManagementController(MenuManagementService managementService, MenuService menuService) {
        this.managementService = managementService;
        this.menuService = menuService;
    }

    @GetMapping("/tree")
    @RequirePermission("system:menu:read")
    public ApiResponse<List<MenuService.MenuNode>> tree() {
        return ApiResponse.ofSuccess(menuService.tree());
    }

    @GetMapping("/{id}")
    @RequirePermission("system:menu:read")
    public ApiResponse<SysMenu> detail(@PathVariable Long id) {
        return ApiResponse.ofSuccess(managementService.detail(id));
    }

    @PostMapping
    @RequirePermission("system:menu:create")
    @OperationLog(operation = "MENU_CREATE", resourceType = "MENU")
    public ApiResponse<SysMenu> create(@RequestBody Map<String, Object> body) {
        return ApiResponse.ofSuccess(managementService.create(
                longOrNull(body.get("parentId")), str(body.get("code")), str(body.get("name")),
                str(body.get("type")), str(body.get("path")), str(body.get("permissionCode")),
                intOrNull(body.get("sort"))));
    }

    @PutMapping("/{id}")
    @RequirePermission("system:menu:update")
    @OperationLog(operation = "MENU_UPDATE", resourceType = "MENU")
    public ApiResponse<SysMenu> update(@PathVariable Long id, @RequestBody Map<String, Object> body) {
        return ApiResponse.ofSuccess(managementService.update(id,
                longOrNull(body.get("parentId")), str(body.get("name")),
                str(body.get("path")), str(body.get("permissionCode")), intOrNull(body.get("sort"))));
    }

    @PostMapping("/{id}/enable")
    @RequirePermission("system:menu:update")
    @OperationLog(operation = "MENU_ENABLE", resourceType = "MENU")
    public ApiResponse<SysMenu> enable(@PathVariable Long id) {
        return ApiResponse.ofSuccess(managementService.setEnabled(id, true));
    }

    @PostMapping("/{id}/disable")
    @RequirePermission("system:menu:disable")
    @OperationLog(operation = "MENU_DISABLE", resourceType = "MENU")
    public ApiResponse<SysMenu> disable(@PathVariable Long id) {
        return ApiResponse.ofSuccess(managementService.setEnabled(id, false));
    }

    private static String str(Object o) {
        return o == null ? null : String.valueOf(o);
    }

    private static Long longOrNull(Object o) {
        if (o == null) {
            return null;
        }
        return o instanceof Number n ? n.longValue() : Long.valueOf(String.valueOf(o));
    }

    private static Integer intOrNull(Object o) {
        if (o == null) {
            return null;
        }
        return o instanceof Number n ? n.intValue() : Integer.valueOf(String.valueOf(o));
    }
}
