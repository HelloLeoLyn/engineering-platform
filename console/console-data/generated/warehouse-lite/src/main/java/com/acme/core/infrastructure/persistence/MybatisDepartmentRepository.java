package com.acme.core.infrastructure.persistence;

import com.acme.core.application.organization.DepartmentPort;
import com.acme.core.domain.entity.SysDepartment;
import com.acme.core.infrastructure.persistence.mapper.SysDepartmentMapper;
import com.baomidou.mybatisplus.core.conditions.query.QueryWrapper;

import java.util.ArrayDeque;
import java.util.ArrayList;
import java.util.Deque;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;

/**
 * MyBatis-Plus implementation of {@link DepartmentPort} (generated by engineering-platform 0.1.0).
 * All MyBatis types stay confined here, in the infrastructure layer.
 */
public class MybatisDepartmentRepository implements DepartmentPort {

    private final SysDepartmentMapper departmentMapper;

    public MybatisDepartmentRepository(SysDepartmentMapper departmentMapper) {
        this.departmentMapper = departmentMapper;
    }

    @Override
    public Optional<SysDepartment> findById(Long departmentId) {
        return Optional.ofNullable(departmentMapper.selectById(departmentId));
    }

    @Override
    public List<SysDepartment> findAll() {
        return departmentMapper.selectList(new QueryWrapper<SysDepartment>().orderByAsc("sort", "id"));
    }

    @Override
    public Set<Long> descendantIds(Long departmentId) {
        List<SysDepartment> all = findAll();
        Map<Long, List<SysDepartment>> byParent = new LinkedHashMap<>();
        for (SysDepartment d : all) {
            if (d.getParentId() == null) {
                continue;
            }
            byParent.computeIfAbsent(d.getParentId(), k -> new ArrayList<>()).add(d);
        }
        Set<Long> result = new LinkedHashSet<>();
        Deque<Long> queue = new ArrayDeque<>();
        queue.add(departmentId);
        while (!queue.isEmpty()) {
            Long current = queue.poll();
            for (SysDepartment child : byParent.getOrDefault(current, List.of())) {
                if (result.add(child.getId())) {
                    queue.add(child.getId());
                }
            }
        }
        return result;
    }
}
