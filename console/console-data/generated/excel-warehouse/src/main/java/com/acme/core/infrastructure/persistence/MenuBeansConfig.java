package com.acme.core.infrastructure.persistence;

import com.acme.core.application.menu.MenuManagementPort;
import com.acme.core.application.menu.MenuManagementService;
import com.acme.core.application.menu.MenuPort;
import com.acme.core.application.menu.MenuService;
import com.acme.core.application.rbac.UserQueryPort;
import com.acme.core.infrastructure.persistence.mapper.SysMenuMapper;
import com.acme.core.infrastructure.persistence.mapper.SysPermissionMapper;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * Menu bean wiring (generated by engineering-platform 0.1.0).
 * MyBatis implementations are wired as the stable application contracts
 * (MenuPort / MenuManagementPort); application services depend only on those
 * contracts.
 */
@Configuration
public class MenuBeansConfig {

    @Bean
    public MenuPort menuPort(SysMenuMapper menuMapper) {
        return new MybatisMenuRepository(menuMapper);
    }

    @Bean
    public MenuService menuService(MenuPort menuPort, UserQueryPort userQueryPort) {
        return new MenuService(menuPort, userQueryPort);
    }

    @Bean
    public MenuManagementPort menuManagementPort(SysMenuMapper menuMapper,
                                                 SysPermissionMapper permissionMapper) {
        return new MybatisMenuManagementRepository(menuMapper, permissionMapper);
    }

    @Bean
    public MenuManagementService menuManagementService(MenuManagementPort menuManagementPort,
                                                       MenuService menuService) {
        return new MenuManagementService(menuManagementPort, menuService);
    }
}
