package com.acme.core.infrastructure.persistence;

import com.acme.core.application.rbac.RoleManagementPort;
import com.acme.core.common.core.PageQuery;
import com.acme.core.common.core.PageResult;
import com.acme.core.domain.entity.SysPermission;
import com.acme.core.domain.entity.SysRole;
import com.acme.core.domain.entity.SysRolePermission;
import com.acme.core.infrastructure.persistence.mapper.SysPermissionMapper;
import com.acme.core.infrastructure.persistence.mapper.SysRoleMapper;
import com.acme.core.infrastructure.persistence.mapper.SysRolePermissionMapper;
import com.baomidou.mybatisplus.core.conditions.query.QueryWrapper;

import java.time.LocalDateTime;
import java.util.List;
import java.util.Optional;

/**
 * MyBatis-Plus implementation of {@link RoleManagementPort} (generated by engineering-platform 0.1.0).
 *
 * All MyBatis-Plus technical types (QueryWrapper / BaseMapper) stay confined
 * here, in the infrastructure layer.
 */
public class MybatisRoleManagementRepository implements RoleManagementPort {

    private final SysRoleMapper roleMapper;
    private final SysRolePermissionMapper rolePermissionMapper;
    private final SysPermissionMapper permissionMapper;

    public MybatisRoleManagementRepository(SysRoleMapper roleMapper,
                                           SysRolePermissionMapper rolePermissionMapper,
                                           SysPermissionMapper permissionMapper) {
        this.roleMapper = roleMapper;
        this.rolePermissionMapper = rolePermissionMapper;
        this.permissionMapper = permissionMapper;
    }

    @Override
    public PageResult<SysRole> page(PageQuery query, String keyword, Boolean enabled) {
        QueryWrapper<SysRole> countWrapper = new QueryWrapper<>();
        applyFilters(countWrapper, keyword, enabled);
        long total = roleMapper.selectCount(countWrapper);
        QueryWrapper<SysRole> wrapper = new QueryWrapper<>();
        applyFilters(wrapper, keyword, enabled);
        wrapper.orderByAsc("id");
        wrapper.last("LIMIT " + query.size() + " OFFSET " + query.offset());
        return PageResult.of(roleMapper.selectList(wrapper), total, query.page(), query.size());
    }

    private void applyFilters(QueryWrapper<SysRole> wrapper, String keyword, Boolean enabled) {
        if (keyword != null && !keyword.isBlank()) {
            wrapper.and(w -> w.like("code", keyword).or().like("name", keyword));
        }
        if (enabled != null) {
            wrapper.eq("enabled", enabled ? 1 : 0);
        }
    }

    @Override
    public Optional<SysRole> findById(Long roleId) {
        return Optional.ofNullable(roleMapper.selectById(roleId));
    }

    @Override
    public Optional<SysRole> findByCode(String code) {
        return Optional.ofNullable(roleMapper.selectOne(
                new QueryWrapper<SysRole>().eq("code", code).last("LIMIT 1")));
    }

    @Override
    public void insert(SysRole role) {
        roleMapper.insert(role);
    }

    @Override
    public void update(SysRole role) {
        roleMapper.updateById(role);
    }

    @Override
    public List<Long> permissionIdsOf(Long roleId) {
        return rolePermissionMapper.selectList(new QueryWrapper<SysRolePermission>()
                        .eq("role_id", roleId))
                .stream().map(SysRolePermission::getPermissionId).toList();
    }

    @Override
    public void replaceRolePermissions(Long roleId, List<Long> permissionIds) {
        rolePermissionMapper.delete(new QueryWrapper<SysRolePermission>().eq("role_id", roleId));
        if (permissionIds == null) {
            return;
        }
        for (Long pid : permissionIds.stream().distinct().toList()) {
            SysRolePermission rp = new SysRolePermission();
            rp.setRoleId(roleId);
            rp.setPermissionId(pid);
            rp.setCreatedAt(LocalDateTime.now());
            rolePermissionMapper.insert(rp);
        }
    }

    @Override
    public Optional<SysPermission> findPermissionById(Long permissionId) {
        return Optional.ofNullable(permissionMapper.selectById(permissionId));
    }
}
