package com.acme.core.api.supplier;

import com.acme.core.application.datascope.DataPermissionContext;
import com.acme.core.application.datascope.DataScopeResolver;
import com.acme.core.application.supplier.SupplierCreateRequest;
import com.acme.core.application.supplier.SupplierResponse;
import com.acme.core.application.supplier.SupplierService;
import com.acme.core.application.supplier.SupplierUpdateRequest;
import com.acme.core.common.core.ApiResponse;
import com.acme.core.common.core.PageQuery;
import com.acme.core.common.core.PageResult;
import com.acme.core.common.core.PlatformException;
import com.acme.core.common.core.RequestContext;
import com.acme.core.common.security.OperationLog;
import com.acme.core.common.security.RequirePermission;
import com.acme.core.common.security.SecurityErrorCodes;
import org.springframework.web.bind.annotation.*;

import java.util.List;

/**
 * Supplier CRUD API (generated by engineering-platform Generic Module Generator).
 */
@RestController
@RequestMapping("/api/supplier")
public class SupplierController {

    private final SupplierService supplierService;
    private final DataScopeResolver dataScopeResolver;

    public SupplierController(SupplierService supplierService, DataScopeResolver dataScopeResolver) {
        this.supplierService = supplierService;
        this.dataScopeResolver = dataScopeResolver;
    }

    private Long currentUserId() {
        return Long.valueOf(RequestContext.currentUserId()
                .orElseThrow(() -> new PlatformException(SecurityErrorCodes.UNAUTHENTICATED)));
    }

    private DataPermissionContext scope() {
        return dataScopeResolver.resolve(currentUserId());
    }

    @PostMapping
    @RequirePermission("supplier:item:create")
    @OperationLog(operation = "SUPPLIER_CREATE", resourceType = "SUPPLIER")
    public ApiResponse<SupplierResponse> create(@RequestBody SupplierCreateRequest request) {
        Long userId = currentUserId();
        Long departmentId = RequestContext.currentDepartmentId().map(Long::valueOf).orElse(null);
        return ApiResponse.ofSuccess(supplierService.create(request, userId, departmentId));
    }

    @GetMapping("/{id}")
    @RequirePermission("supplier:item:read")
    public ApiResponse<SupplierResponse> detail(@PathVariable Long id) {
        return ApiResponse.ofSuccess(supplierService.get(id, scope()));
    }

    @GetMapping
    @RequirePermission("supplier:item:read")
    public ApiResponse<PageResult<SupplierResponse>> list(
            @RequestParam(defaultValue = "1") int page,
            @RequestParam(defaultValue = "20") int size,
            @RequestParam(required = false) String keyword,
            @RequestParam(required = false) String status) {
        return ApiResponse.ofSuccess(supplierService.pageFiltered(PageQuery.of(page, size), scope(), keyword, status));
    }

    @PutMapping("/{id}")
    @RequirePermission("supplier:item:update")
    @OperationLog(operation = "SUPPLIER_UPDATE", resourceType = "SUPPLIER")
    public ApiResponse<SupplierResponse> update(@PathVariable Long id, @RequestBody SupplierUpdateRequest request) {
        return ApiResponse.ofSuccess(supplierService.update(id, request, scope()));
    }

    @PostMapping("/{id}/disable")
    @RequirePermission("supplier:item:disable")
    @OperationLog(operation = "SUPPLIER_DISABLE", resourceType = "SUPPLIER")
    public ApiResponse<SupplierResponse> disable(@PathVariable Long id) {
        return ApiResponse.ofSuccess(supplierService.disable(id, scope()));
    }
}
