package com.acme.core.infrastructure.persistence;

import com.acme.core.application.warehouse.WarehousePort;
import com.acme.core.application.datascope.DataPermissionContext;
import com.acme.core.application.organization.DepartmentPort;
import com.acme.core.common.core.PageQuery;
import com.acme.core.common.core.PageResult;
import com.acme.core.common.security.DataScope;
import com.acme.core.domain.entity.Warehouse;
import com.acme.core.infrastructure.persistence.mapper.WarehouseMapper;
import com.baomidou.mybatisplus.core.conditions.query.QueryWrapper;

import java.util.List;
import java.util.Optional;
import java.util.Set;

/**
 * MyBatis-Plus implementation of {@link WarehousePort} (generated by engineering-platform Generic Module Generator).
 * Data scope enforcement happens HERE at the query boundary: ALL / DEPARTMENT /
 * DEPARTMENT_AND_CHILDREN / SELF. Fail-safe: missing department with a department-
 * dependent scope denies (empty), never upgrades to ALL.
 */
public class MybatisWarehouseRepository implements WarehousePort {

    private final WarehouseMapper warehouseMapper;
    private final DepartmentPort departmentPort;

    public MybatisWarehouseRepository(WarehouseMapper warehouseMapper, DepartmentPort departmentPort) {
        this.warehouseMapper = warehouseMapper;
        this.departmentPort = departmentPort;
    }

    @Override
    public Optional<Warehouse> findById(Long id) {
        return Optional.ofNullable(warehouseMapper.selectById(id));
    }

    @Override
    public Optional<Warehouse> findByIdInScope(Long id, DataPermissionContext context) {
        return findByScope(context).stream().filter(e -> e.getId().equals(id)).findFirst();
    }

    @Override
    public List<Warehouse> findByScope(DataPermissionContext context) {
        QueryWrapper<Warehouse> wrapper = scopeWrapper(context);
        wrapper.orderByAsc("id");
        return warehouseMapper.selectList(wrapper);
    }

    @Override
    public PageResult<Warehouse> findPageByScope(DataPermissionContext context, PageQuery query) {
        QueryWrapper<Warehouse> countWrapper = scopeWrapper(context);
        long total = warehouseMapper.selectCount(countWrapper);
        QueryWrapper<Warehouse> pageWrapper = scopeWrapper(context);
        pageWrapper.orderByAsc("id");
        pageWrapper.last("LIMIT " + query.size() + " OFFSET " + query.offset());
        List<Warehouse> items = warehouseMapper.selectList(pageWrapper);
        return PageResult.of(items, total, query.page(), query.size());
    }

    @Override
    public PageResult<Warehouse> findPageByScopeFiltered(DataPermissionContext context, PageQuery query, String keyword, String status, String code, String name) {
        QueryWrapper<Warehouse> countWrapper = scopeWrapper(context);
        applyFilters(countWrapper, keyword, status, code, name);
        long total = warehouseMapper.selectCount(countWrapper);
        QueryWrapper<Warehouse> pageWrapper = scopeWrapper(context);
        applyFilters(pageWrapper, keyword, status, code, name);
        pageWrapper.orderByAsc("id");
        pageWrapper.last("LIMIT " + query.size() + " OFFSET " + query.offset());
        List<Warehouse> items = warehouseMapper.selectList(pageWrapper);
        return PageResult.of(items, total, query.page(), query.size());
    }

    private void applyFilters(QueryWrapper<Warehouse> wrapper, String keyword, String status, String code, String name) {
        if (code != null && !code.isBlank()) {
            wrapper.like("code", code);
        }
        if (name != null && !name.isBlank()) {
            wrapper.like("name", name);
        }
        if (keyword != null && !keyword.isBlank()) {
            wrapper.and(w -> {w.like("code", keyword) .or().like("name", keyword) .or().like("address", keyword) .or().like("manager", keyword) .or().like("status", keyword); });
        }
        if (status != null && !status.isBlank()) {
            wrapper.eq("status", status);
        }
    }

    private QueryWrapper<Warehouse> scopeWrapper(DataPermissionContext context) {
        QueryWrapper<Warehouse> wrapper = new QueryWrapper<>();
        DataScope scope = context.scope() == null ? DataScope.SELF : context.scope();
        switch (scope) {
            case ALL -> { }
            case DEPARTMENT -> {
                if (context.departmentId() == null) { wrapper.eq("id", -1L); } else { wrapper.eq("department_id", context.departmentId()); }
            }
            case DEPARTMENT_AND_CHILDREN -> {
                if (context.departmentId() == null) { wrapper.eq("id", -1L); } else {
                    Set<Long> ids = departmentPort.descendantIds(context.departmentId());
                    ids.add(context.departmentId());
                    wrapper.in("department_id", ids);
                }
            }
            case SELF -> {
                if (context.userId() == null) { wrapper.eq("id", -1L); } else { wrapper.eq("created_by", String.valueOf(context.userId())); }
            }
        }
        return wrapper;
    }

    @Override
    public boolean existsByUnique(String value, Long excludeId) {
        QueryWrapper<Warehouse> wrapper = new QueryWrapper<>();
        wrapper.eq("code", value);
        if (excludeId != null) { wrapper.ne("id", excludeId); }
        return warehouseMapper.selectCount(wrapper) > 0;
    }

    @Override
    public Warehouse insert(Warehouse entity) {
        warehouseMapper.insert(entity);
        return entity;
    }

    @Override
    public int update(Warehouse entity) {
        return warehouseMapper.updateById(entity);
    }
}
