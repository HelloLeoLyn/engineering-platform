package com.acme.core.api.customer;

import com.acme.core.application.datascope.DataPermissionContext;
import com.acme.core.application.datascope.DataScopeResolver;
import com.acme.core.application.customer.CustomerCreateRequest;
import com.acme.core.application.customer.CustomerResponse;
import com.acme.core.application.customer.CustomerService;
import com.acme.core.application.customer.CustomerUpdateRequest;
import com.acme.core.common.core.ApiResponse;
import com.acme.core.common.core.PageQuery;
import com.acme.core.common.core.PageResult;
import com.acme.core.common.core.PlatformException;
import com.acme.core.common.core.RequestContext;
import com.acme.core.common.security.OperationLog;
import com.acme.core.common.security.RequirePermission;
import com.acme.core.common.security.SecurityErrorCodes;
import org.springframework.web.bind.annotation.*;

import java.util.List;

/**
 * Customer CRUD API (generated by engineering-platform Generic Module Generator).
 */
@RestController
@RequestMapping("/api/customer")
public class CustomerController {

    private final CustomerService customerService;
    private final DataScopeResolver dataScopeResolver;

    public CustomerController(CustomerService customerService, DataScopeResolver dataScopeResolver) {
        this.customerService = customerService;
        this.dataScopeResolver = dataScopeResolver;
    }

    private Long currentUserId() {
        return Long.valueOf(RequestContext.currentUserId()
                .orElseThrow(() -> new PlatformException(SecurityErrorCodes.UNAUTHENTICATED)));
    }

    private DataPermissionContext scope() {
        return dataScopeResolver.resolve(currentUserId());
    }

    @PostMapping
    @RequirePermission("customer:item:create")
    @OperationLog(operation = "CUSTOMER_CREATE", resourceType = "CUSTOMER")
    public ApiResponse<CustomerResponse> create(@RequestBody CustomerCreateRequest request) {
        Long userId = currentUserId();
        Long departmentId = scope().departmentId();
        return ApiResponse.ofSuccess(customerService.create(request, userId, departmentId));
    }

    @GetMapping("/{id}")
    @RequirePermission("customer:item:read")
    public ApiResponse<CustomerResponse> detail(@PathVariable Long id) {
        return ApiResponse.ofSuccess(customerService.get(id, scope()));
    }

    @GetMapping
    @RequirePermission("customer:item:read")
    public ApiResponse<PageResult<CustomerResponse>> list(
            @RequestParam(defaultValue = "1") int page,
            @RequestParam(defaultValue = "20") int size,
            @RequestParam(required = false) String keyword,
            @RequestParam(required = false) String status,
            @RequestParam(required = false) String code,
            @RequestParam(required = false) String name) {
        return ApiResponse.ofSuccess(customerService.pageFiltered(PageQuery.of(page, size), scope(), keyword, status, code, name));
    }

    @PutMapping("/{id}")
    @RequirePermission("customer:item:update")
    @OperationLog(operation = "CUSTOMER_UPDATE", resourceType = "CUSTOMER")
    public ApiResponse<CustomerResponse> update(@PathVariable Long id, @RequestBody CustomerUpdateRequest request) {
        return ApiResponse.ofSuccess(customerService.update(id, request, scope()));
    }

    @PostMapping("/{id}/disable")
    @RequirePermission("customer:item:disable")
    @OperationLog(operation = "CUSTOMER_DISABLE", resourceType = "CUSTOMER")
    public ApiResponse<CustomerResponse> disable(@PathVariable Long id) {
        return ApiResponse.ofSuccess(customerService.disable(id, scope()));
    }
}
